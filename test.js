'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const products = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/products.json'), 'utf8'));
const app = require('../app.js');
app.setProducts(products);
const ids = products.map(p => p.id);
assert.equal(new Set(ids).size, ids.length, '產品 id 必須唯一');
assert.ok(products.length >= 1, '產品資料不可為空');
const dali = products.find(p => p.id === 'dali-sonik-1');
assert.ok(dali, '必須包含 DALI SONIK 1');
assert.equal(dali.brand, 'DALI');
assert.equal(dali.specs.impedance, '6 Ω');
assert.equal(dali.specs.sensitivity, '86 dB (2.83V/1m)');
assert.match(dali.source, /^https:\/\//);
assert.equal(dali.priceTwd, null, '未確認台灣價格時應保持 null');
assert.equal(app.categoryName('speaker'), '喇叭');
const sampleProfile = {budget:30000,speakerBudget:15000,room:'small',source:'vinyl',sound:'warm'};
const recommendations = app.buildRecommendations(sampleProfile);
assert.equal(recommendations.length, 3, '必須回傳三套推薦');
assert.ok(recommendations.every(r => r.reason.includes('黑膠')),'推薦理由需考慮訊源');
assert.ok(recommendations.every(r => r.compatibility.includes('需以選定擴大機原廠規格確認')),'未知相容性必須明確標示');
console.log(`PASS: ${products.length} 筆產品資料、唯一 ID、DALI SONIK 1、三套推薦與相容性提醒。`);
